// Collects the labels for the "git graph" page background: the subjects of this repo's recent
// commits, made short and plain (no "feat:" prefix, no hashes, at most 30 characters, cut at a word).
// Written to src/constants/commits.js as the first step of the build. If git is not available the file
// that is already there is kept, so the build never fails because of this.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "constants", "commits.js");
const MAX = 30;
const KEEP = 12;

const shorten = (subject) => {
  let s = subject
    .replace(/^\w+(\([^)]*\))?!?:\s*/, "") // "feat(scope): "
    .replace(/https?:\/\/\S+/g, "")
    .replace(/\b[0-9a-f]{7,40}\b/g, "")
    .replace(/\s+/g, " ")
    .trim();
  if (s.length > MAX) s = s.slice(0, MAX + 1).replace(/\s+\S*$/, "");
  // never end on a dangling word ("... component for")
  return s.replace(/(\s+(for|to|and|with|of|the|a|an|in|on|from|by|that))+$/i, "").trim();
};

try {
  const raw = execFileSync("git", ["log", "-n", "80", "--no-merges", "--pretty=%s"], { encoding: "utf-8", stdio: ["ignore", "pipe", "ignore"] });
  const seen = new Set();
  const labels = [];
  for (const line of raw.split("\n")) {
    const s = shorten(line);
    if (s.length < 6 || seen.has(s.toLowerCase())) continue;
    seen.add(s.toLowerCase());
    labels.push(s);
    if (labels.length === KEEP) break;
  }
  if (labels.length) {
    fs.writeFileSync(
      OUT,
      `// GENERATED by scripts/commits.mjs (the first step of \`npm run build\`). Do not edit.\n// Short labels from this repo's recent commit messages, for the git-graph page background.\nexport const COMMIT_LABELS = ${JSON.stringify(labels, null, 2)};\n`
    );
    console.log(`commits.mjs: ${labels.length} labels`);
  }
} catch {
  console.log("commits.mjs: git not available, keeping src/constants/commits.js");
}
