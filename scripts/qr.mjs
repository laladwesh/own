// Makes the QR code for the one-page summary (the "full site" link in its footer) as one SVG path,
// written to src/constants/qr.js. It runs as the first step of the build, so the code always
// matches the site address. No browser, no runtime library: the page only uses the path string.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import QRCode from "qrcode";

const URL_TO_ENCODE = "https://avinashgupta.in";
const qr = QRCode.create(URL_TO_ENCODE, { errorCorrectionLevel: "M" });
const n = qr.modules.size;

// Horizontal runs of dark modules: "M x y h<run> v1 h-<run> z".
const parts = [];
for (let y = 0; y < n; y++) {
  let x = 0;
  while (x < n) {
    if (!qr.modules.get(y, x)) {
      x += 1;
      continue;
    }
    let run = 1;
    while (x + run < n && qr.modules.get(y, x + run)) run += 1;
    parts.push(`M${x} ${y}h${run}v1h-${run}z`);
    x += run;
  }
}

const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "constants", "qr.js");
fs.writeFileSync(
  out,
  `// Generated by scripts/qr.mjs (do not edit): the QR code for ${URL_TO_ENCODE} as one SVG path.\nexport const QR_URL = ${JSON.stringify(URL_TO_ENCODE)};\nexport const QR_SIZE = ${n};\nexport const QR_PATH = ${JSON.stringify(parts.join(""))};\n`
);
console.log(`qr: src/constants/qr.js (${n}x${n} modules)`);
